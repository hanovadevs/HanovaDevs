import { test, expect } from '@playwright/test'

async function expectContained(locator, page) {
  await expect(locator).toBeVisible()
  const bounds = await locator.boundingBox()
  const viewport = page.viewportSize()
  expect(bounds.x).toBeGreaterThanOrEqual(-1)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(viewport.width + 1)
}

test('hero and company LinkedIn link fit the screen', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Web platforms and growth systems.' })).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  const headlines = page.locator('.hero__headline-line')
  await expect(headlines).toHaveCount(2)
  for (const headline of await headlines.all()) {
    await expectContained(headline, page)
    expect(await headline.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBeTruthy()
  }
  await expectContained(page.getByRole('link', { name: 'Start a Project', exact: true }), page)
  await expect(page.locator('footer').getByRole('link', { name: 'LinkedIn', exact: true })).toHaveAttribute('href', 'https://www.linkedin.com/company/hanova-devs')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBeTruthy()
})

test('mobile menu is scrollable, supports Escape, and closes on navigation and desktop resize', async ({ page }) => {
  test.skip(page.viewportSize().width > 1120, 'Desktop uses the inline navigation')
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const toggle = page.locator('#mobile-menu-toggle')
  const menu = page.locator('#mobile-navigation')
  await toggle.click()
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('link', { name: 'Home', exact: true })).toBeFocused()
  const bounds = await menu.boundingBox()
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(page.viewportSize().height)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.keyboard.press('Escape')
  await expect(toggle).toBeFocused()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click()
  const quote = menu.getByRole('link', { name: 'Get a Quote' })
  await quote.focus()
  await page.keyboard.press('Tab')
  await expect(toggle).toBeFocused()
  await quote.click()
  await expect(page).toHaveURL('/contact')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  await toggle.click()
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(menu).toBeHidden()
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
})

test('news search, saved stories, and summaries work on touch layouts', async ({ page }) => {
  await page.goto('/news', { waitUntil: 'domcontentloaded' })
  const search = page.getByRole('searchbox', { name: 'Search news' })
  await search.fill('a-story-that-does-not-exist')
  await expect(page.getByRole('heading', { name: 'No matching stories' })).toBeVisible()
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await search.fill('Anthropic')
  const save = page.locator('.nw2-lead .nw2-save')
  await save.click()
  await expect(save).toHaveAttribute('aria-pressed', 'true')
  await search.clear()
  await page.getByRole('button', { name: 'Saved', exact: true }).click()
  await expect(page.locator('.nw2-feed__header > p')).toHaveText('1 story')
  await page.getByRole('button', { name: 'Quick read', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expectContained(dialog, page)
  const bounds = await dialog.boundingBox()
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(page.viewportSize().height + 1)
  await page.getByRole('button', { name: 'Close article summary' }).click()
  await expect(dialog).toHaveCount(0)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Saved', exact: true }).click()
  await expect(page.locator('.nw2-feed__header > p')).toHaveText('1 story')
})

test('gallery selection reaches the last thumbnail without page overflow', async ({ page }) => {
  await page.goto('/products/eunoia', { waitUntil: 'domcontentloaded' })
  const mainImage = page.locator('.ed-gallery__main-img')
  const previous = await mainImage.getAttribute('src')
  const last = page.locator('.ed-gallery__thumb').last()
  await last.click()
  await expect(last).toHaveClass(/ed-gallery__thumb--active/)
  await expect(mainImage).not.toHaveAttribute('src', previous)
  await expectContained(page.locator('.ed-gallery__viewer'), page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBeTruthy()
})

test('estimator controls update the displayed quote on mobile', async ({ page }) => {
  await page.goto('/calculator', { waitUntil: 'domcontentloaded' })
  await page.locator('.calc-tab-btn').last().click()
  const total = page.locator('.summary-value.gradient-text')
  await expect(total).toBeVisible()
  const previous = await total.textContent()
  const pages = page.locator('.calc-card input[type="range"]').first()
  await pages.fill('20')
  await expect(total).not.toHaveText(previous)
  await expectContained(total, page)
})

test('assistant and mobile form fields stay usable in a short viewport', async ({ page }) => {
  await page.goto('/contact', { waitUntil: 'domcontentloaded' })
  const fields = page.locator('.contact-form input, .contact-form select, .contact-form textarea')
  await expect(fields.first()).toBeVisible()
  if (page.viewportSize().width <= 768) {
    for (const field of await fields.all()) expect(await field.evaluate(element => parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(16)
  }
  await page.getByRole('button', { name: 'Toggle AI Assistant' }).click()
  const panel = page.locator('#ai-assistant-panel')
  await expectContained(panel, page)
  const bounds = await panel.boundingBox()
  expect(bounds.y).toBeGreaterThanOrEqual(0)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(page.viewportSize().height)
  await page.getByRole('textbox', { name: 'Message Aria' }).fill('Hello')
  await expect(page.getByRole('textbox', { name: 'Message Aria' })).toHaveValue('Hello')
  await page.getByRole('button', { name: 'Toggle AI Assistant' }).click()
  await expect(panel).toHaveAttribute('inert', '')
})
